// Parse plain text to extract fields heuristically (no extra API call needed)
function parseLeadFromHistory() {
  var fullText = popupHistory.map(function(m) {
    return (m.role === "user" ? "CLIENTE: " : "ASESOR: ") + m.content;
  }).join(" | ");

  // nombre: look for "me llamo X", "soy X", "mi nombre es X"
  var mNombre = fullText.match(/(?:me llamo|soy|mi nombre es|nombre[: ]+)([A-Z][a-zA-ZáéíóúÁÉÍÓÚñÑ ]{2,25})(?=[,. |]|$)/i);
  if (mNombre) leadData.nombre = mNombre[1].trim();

  // telefono: look for phone-like numbers
  var mTel = fullText.match(/(?:tel[eé]fono[: ]+|n[uú]mero[: ]+|whatsapp[: ]+|cel[ular]*[: ]+|al |es )([+0-9][0-9 \-]{6,18})/i);
  if (mTel) leadData.telefono = mTel[1].trim();

  // vehiculo: look for brand/model patterns
  var mVeh = fullText.match(/(?:tengo (?:un |una )?|mi (?:auto|carro|coche|vehículo) es (?:un |una )?|mi |es (?:un |una )?)([A-Z][a-zA-Z]+(?: [A-Z][a-zA-Z0-9]+){0,4}(?:(?: \d{4})?))(?=[,. |])/i);
  // Also try user messages that just mention the car
  var userMsgs = popupHistory.filter(function(m){ return m.role==="user"; }).map(function(m){ return m.content; }).join(" ");
  var mVeh2 = userMsgs.match(/(Toyota|Honda|Chevrolet|Ford|Volkswagen|VW|Mazda|Mitsubishi|Nissan|Subaru|BMW|Mercedes|Audi|Hyundai|Kia|Dodge|Jeep|RAM|Tesla|Porsche|Ferrari|Lamborghini|Maserati|Alfa|Fiat|Peugeot|Renault|Citroën|Seat|Skoda|Volvo|Land Rover|Range Rover|Lexus|Infiniti|Acura|Cadillac|Buick|Lincoln|GMC|Chrysler|Mini|Smart|Dacia|Lada)[^,.|]{0,40}/i);
  if (mVeh2) leadData.vehiculo = mVeh2[0].trim();
  else if (mVeh) leadData.vehiculo = mVeh[1].trim();

  // Extract vehicle info from asesor summaries (more reliable)
  var asorTexts = popupHistory.filter(function(m){ return m.role==="assistant"; }).map(function(m){ return m.content; }).join(" ");
  var mVehAsesor = asorTexts.match(/(?:tu |el |con (?:un |una )?)([A-Z][a-zA-Z]+(?: [A-Z][a-zA-Z0-9]+){1,4}(?:(?: \d{4})))/);
  if (!leadData.vehiculo && mVehAsesor) leadData.vehiculo = mVehAsesor[1].trim();

  // servicio: look in asesor closing message
  var mSvc = asorTexts.match(/coordinar tu ([^.!]+?)(?:\.|!)/i);
  if (mSvc) leadData.servicio = mSvc[1].trim();

  // detalle: take first user message
  if (popupHistory.length > 0) {
    var firstUser = popupHistory.find(function(m){ return m.role==="user"; });
    if (firstUser) leadData.detalle = firstUser.content.substring(0, 120);
  }
}

